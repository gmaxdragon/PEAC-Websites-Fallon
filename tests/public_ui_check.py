"""Responsive, reversible page-theme regression tests using disposable local data.
No real forms are submitted. Screenshots are generated by browsers, not mockups.
"""
from __future__ import annotations
import json
import os
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from peac_community import CommunityService

OUT = ROOT / 'test-artifacts'
OUT.mkdir(exist_ok=True)
BASE = os.getenv('PEAC_TEST_URL', 'http://127.0.0.1:5000').rstrip('/')


def settle(page):
    page.evaluate('() => new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r)))')


def scroll_boundary(page, offset):
    page.evaluate('''offset => {
        const vv = visualViewport;
        const line = (vv?.offsetTop || 0) + Math.min(300, Math.max(120, (vv?.height || innerHeight) * .42));
        const y = document.getElementById('feedback').getBoundingClientRect().top + scrollY;
        scrollTo({top:y - line + offset, behavior:'instant'});
    }''', offset)
    settle(page)


def check_theme(page, theme):
    expect(page.locator('html')).to_have_attribute('data-peac-theme', theme)
    color = 'rgb(16, 47, 39)' if theme == 'dark' else 'rgb(248, 250, 244)'
    page.wait_for_function('(color) => getComputedStyle(document.body).backgroundColor === color', arg=color)
    assert page.locator('meta[name="theme-color"]').get_attribute('content') == ('#102f27' if theme == 'dark' else '#f8faf4')
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1'), 'Horizontal overflow'


def check_readability(page):
    ratios = page.evaluate('''() => {
        function rgb(value) { return (value.match(/[\\d.]+/g) || []).map(Number); }
        function luminance(c) {
            const x=c.slice(0,3).map(v => {v/=255; return v<=.04045?v/12.92:((v+.055)/1.055)**2.4;});
            return .2126*x[0]+.7152*x[1]+.0722*x[2];
        }
        function background(el) {
            const layers=[];
            for (let e=el;e;e=e.parentElement) layers.push(rgb(getComputedStyle(e).backgroundColor));
            let c=[255,255,255];
            for (const layer of layers.reverse()) {
                const a=layer.length>3?layer[3]:1;
                c=c.map((v,i)=>layer[i]*a+v*(1-a));
            }
            return c;
        }
        return ['#feedback h2','#feedback .section-heading>p','#publicFeedbackText',
          '#publicFeedbackBtn','.future-heading h2','.future-heading p','.future-card h3',
          '.future-card p','.future-footer p','.footer-privacy'].map(selector=>{
            const e=document.querySelector(selector), a=luminance(rgb(getComputedStyle(e).color)),b=luminance(background(e));
            return {selector,ratio:(Math.max(a,b)+.05)/(Math.min(a,b)+.05)};
        });
    }''')
    for item in ratios:
        assert item['ratio'] >= 4.5, item
    return ratios


def check_breathing(page):
    # Programmatic activation lets us verify the dark context without scrolling
    # to the header (which correctly switches the page back to the light theme).
    page.locator('[data-open-breathing]').first.evaluate('(e) => e.click()')
    dialog = page.locator('#breathingDialog')
    expect(dialog).to_be_visible()
    dialog.get_by_role('button', name='Start 3 rounds', exact=True).click()
    expect(dialog).to_have_attribute('data-breathing-state', 'running')
    dialog.get_by_role('button', name='Pause', exact=True).click()
    expect(dialog).to_have_attribute('data-breathing-state', 'paused')
    dialog.get_by_role('button', name='Restart', exact=True).click()
    expect(dialog).to_have_attribute('data-breathing-state', 'running')
    dialog.get_by_role('button', name='End session', exact=True).click()
    expect(dialog).not_to_be_visible()
    settle(page)


def browser_cases(browser, engine, cases, report):
    for width, height, touch in cases:
        name = f'{engine}-{width}x{height}'
        context = browser.new_context(viewport={'width':width,'height':height},
                                      is_mobile=touch,has_touch=touch,reduced_motion='reduce')
        page = context.new_page()
        errors, writes = [], []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.on('request', lambda r: writes.append(r.url) if r.method not in ('GET','HEAD','OPTIONS') else None)
        try:
            response = page.goto(BASE, wait_until='networkidle')
            assert response.status == 200
            page.evaluate("scrollTo({top:0,behavior:'instant'})")
            check_theme(page, 'light')
            expect(page.locator('html')).to_have_attribute('data-theme-revision','2026.10.22.1')
            expect(page.locator('.future-card')).to_have_count(6)
            expect(page.locator('.symbol-trail')).to_have_count(7)
            assert page.locator('.symbol-trail').evaluate_all('(es)=>es.every(e=>e.getAttribute("aria-hidden")==="true" && getComputedStyle(e).pointerEvents==="none")')
            ids=page.locator('[id]').evaluate_all('(es)=>es.map(e=>e.id)')
            assert len(ids)==len(set(ids))
            assert page.locator('a[href^="#"]').evaluate_all('(es)=>es.every(e=>!!document.getElementById(e.hash.slice(1)))')
            if width in (390,1440):
                page.screenshot(path=str(OUT/f'light-{name}.png'),animations='disabled')
            before_y = page.locator('#feedback').evaluate('(e)=>e.getBoundingClientRect().top+scrollY')
            scroll_boundary(page, -80)
            check_theme(page, 'light')
            scroll_boundary(page, 80)
            check_theme(page, 'dark')
            after_y = page.locator('#feedback').evaluate('(e)=>e.getBoundingClientRect().top+scrollY')
            assert abs(after_y-before_y) < 1, f'Theme moved its own boundary: {before_y} vs {after_y}'
            ratios=check_readability(page)
            # A small movement at the exact line must not flicker the theme.
            for delta in (0,5,-5,3):
                scroll_boundary(page,delta)
                check_theme(page,'dark')
            scroll_boundary(page,-80)
            check_theme(page,'light')
            scroll_boundary(page,0)
            check_theme(page,'light')
            scroll_boundary(page,80)
            check_theme(page,'dark')
            if width in (390,1440):
                page.screenshot(path=str(OUT/f'divider-{name}.png'),animations='disabled')
            field=page.locator('#publicFeedbackText')
            field.fill('Local UI test draft. Do not submit.')
            expect(field).to_be_focused()
            if width<=760:
                assert field.evaluate('(e)=>parseFloat(getComputedStyle(e).fontSize)')>=16
                assert page.locator('#publicFeedbackBtn').bounding_box()['height']>=44
            # Approximate keyboard-height change while editing, without data loss.
            page.set_viewport_size({'width':width,'height':max(320,height-200)})
            settle(page)
            check_theme(page,'dark')
            expect(field).to_have_value('Local UI test draft. Do not submit.')
            field.blur()
            page.set_viewport_size({'width':width,'height':height})
            page.evaluate("scrollTo({top:document.documentElement.scrollHeight,behavior:'instant'})")
            settle(page)
            check_theme(page,'dark')
            page.locator('#programs').screenshot(path=str(OUT/f'coming-soon-{name}.png'),animations='disabled')
            check_breathing(page)
            page.evaluate("scrollTo({top:0,behavior:'instant'})")
            settle(page)
            check_theme(page,'light')
            expect(field).to_have_value('Local UI test draft. Do not submit.')
            # Deep links/reloads must derive the theme from position, not memory.
            page.goto(BASE+'/#programs',wait_until='networkidle')
            check_theme(page,'dark')
            page.reload(wait_until='networkidle')
            check_theme(page,'dark')
            page.evaluate("scrollTo({top:0,behavior:'instant'})")
            settle(page)
            check_theme(page,'light')
            assert not errors, errors
            assert not writes, writes
            report.append({'case':name,'status':'passed','contrast':ratios})
            print(f'PASS {name}: reversible global theme, stable threshold, responsive layout, drafts, links, contrast, breathing',flush=True)
        except Exception:
            page.screenshot(path=str(OUT/f'FAIL-{name}.png'),full_page=True,animations='disabled')
            raise
        finally:
            context.close()


def run_browser_tests(report):
    with sync_playwright() as p:
        with p.chromium.launch() as browser:
            browser_cases(browser,'chromium',[(1440,1000,False),(1920,1080,False),(1024,768,False),
                (768,1024,True),(430,932,True),(390,844,True),(320,700,True),(844,390,True)],report)
            page=browser.new_page(viewport={'width':1440,'height':1000},reduced_motion='no-preference')
            page.goto(BASE,wait_until='networkidle')
            scroll_boundary(page,80)
            check_theme(page,'dark')
            assert page.locator('body').evaluate('(e)=>getComputedStyle(e).transitionDuration')!='0s'
            page.locator('#motionToggle').click()
            expect(page.locator('html')).to_have_attribute('data-motion','off')
            assert page.locator('body').evaluate('(e)=>getComputedStyle(e).transitionDuration')=='0s'
            page.evaluate("scrollTo({top:0,behavior:'instant'})")
            settle(page)
            check_theme(page,'light')
            print('PASS animated color transition and manual reduced-motion setting',flush=True)
        with p.webkit.launch() as browser:
            browser_cases(browser,'webkit',[(390,844,True),(844,390,True),(1440,1000,False)],report)


def main():
    report=[]
    try:
        if os.getenv('PEAC_TEST_URL'):
            run_browser_tests(report)
            return
        with tempfile.TemporaryDirectory(prefix='peac-ui-') as temp:
            database=Path(temp)/'peac.sqlite3'
            service=CommunityService(database)
            service.auth.create_user({'username':'ui-test-admin','display_name':'UI Test',
                'password':'UI-test-only-password-12345','role':'admin'},'test')
            env={**os.environ,'PEAC_DEPLOY_MODE':'','PEAC_HOST':'127.0.0.1','PEAC_PORT':'5000','PEAC_DB_PATH':str(database)}
            with (OUT/'server.log').open('w') as log:
                server=subprocess.Popen([sys.executable,'peac.py','--local-server'],cwd=ROOT,env=env,stdout=log,stderr=log)
                try:
                    for _ in range(60):
                        if server.poll() is not None:
                            raise RuntimeError((OUT/'server.log').read_text())
                        try:
                            with urllib.request.urlopen(BASE+'/api/health',timeout=1) as r:
                                assert r.status==200
                            break
                        except OSError:
                            time.sleep(.25)
                    else:
                        raise RuntimeError('Local server did not become healthy')
                    run_browser_tests(report)
                finally:
                    server.terminate()
                    try:
                        server.wait(timeout=8)
                    except subprocess.TimeoutExpired:
                        server.kill()
                        server.wait()
    finally:
        (OUT/'results.json').write_text(json.dumps(report,indent=2))

if __name__=='__main__':
    main()
